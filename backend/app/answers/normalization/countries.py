_PAREN_CODE_RE = re.compile(r"\(([A-Za-z]{2})\)")


def _strip_accents_and_fold(text: str) -> str:
    decomposed = unicodedata.normalize("NFKD", text)
    stripped = "".join(ch for ch in decomposed if not unicodedata.combining(ch))
    # Turkish dotless 'ı' is not a combining mark; fold to 'i' so 'türkiye'/'mısır' match.
    stripped = stripped.replace("ı", "i").replace("ß", "ss")
    return " ".join(stripped.strip().lower().split())


def normalize_country_value(raw_val: object) -> str:
    """Normalize ISO codes, country names, and demonyms to ISO 3166-1 alpha-2."""
    raw = str(raw_val).strip()
    if not raw:
        return ""

    if len(raw) == 2 and raw.isascii() and raw.isalpha():
        return raw.upper()

    folded = _strip_accents_and_fold(raw)
    if folded in _COUNTRY_NAME_TO_ISO2:
        return _COUNTRY_NAME_TO_ISO2[folded]

    paren_match = _PAREN_CODE_RE.search(raw)
    if paren_match:
        return paren_match.group(1).upper()

    # Handle composite strings like "German / Deutsch" or "Germany - DE"
    for token in re.split(r"[/,;|\-()]+", raw):
        cleaned = _strip_accents_and_fold(token)
        if not cleaned:
            continue
        if cleaned in _COUNTRY_NAME_TO_ISO2:
            return _COUNTRY_NAME_TO_ISO2[cleaned]
        if len(cleaned) == 2 and cleaned.isascii() and cleaned.isalpha():
            return cleaned.upper()

    return raw.upper()
